def _parse_export_file(text: str, source: Path) -> tuple[list[PlannedNote], list[tuple[Path, int, str]]]:
    """Parse a vectr export file (`render_memory_markdown()` output)
    into a list of `PlannedNote` objects. Reuses `parse_edit_buffer()`
    rather than re-deriving the block grammar — the export is the
    SAME buffer grammar `vectr memory edit` consumes, so the parser
    is the parser.

    Each parsed block has its `kind`, `priority`, `tags`, `provenance`,
    and (if present) `author_id` carried forward from the rendered
    metadata bullets, then turned into a `remember()` call that
    re-creates the original note. The block's `[#N]` heading anchor
    is NOT preserved (a re-import has no guarantee the original
    note_id is still free — and the note_id is purely the database's
    primary key, not a semantic identifier).

    A parsed block whose body is empty after `parse_edit_buffer()` is
    dropped with a parse_error row: it means a corrupt block boundary
    in the export, which the export's own determinism contract says
    cannot happen but a hand-edited file could still produce.
    """

    planned: list[PlannedNote] = []
    errors: list[tuple[Path, int, str]] = []
    try:
        blocks = parse_edit_buffer(text)
    except Exception as exc:  # parse_edit_buffer raises MemoryEditParseError
        errors.append((source, 1, f"could not parse export file: {exc}"))
        return planned, errors

    # The export header comment line is the first line of `text`. We
    # track the per-block start_line by counting the `# ` boundaries
    # encountered before each `### ` block, since the export grammar
    # uses both `##` (kind section) and `###` (note heading).
    boundary_pattern = re.compile(r"^(#{2,3}) .+$", re.MULTILINE)
    block_starts: list[int] = []
    for m in boundary_pattern.finditer(text):
        marker = m.group(1)
        if marker == "###":
            block_starts.append(text[: m.start()].count("\n") + 1)
    block_iter = iter(block_starts)

    for block in blocks:
        # `block.note_id is None` means a `### Title` block with no
        # `[#N]` anchor — not a valid export shape (the export grammar
        # always emits an anchor). We skip these with a parse_error
        # rather than treating them as fresh notes: an export file
        # with anchor-less blocks is either hand-edited or corrupt,
        # and a user who wants to import a non-export file would
        # point at a non-export file.
        if block.note_id is None:
            errors.append((source, 0, "export block missing [#N] anchor; not a valid vectr export"))
            continue
        body = block.body.strip()
        if not body:
            errors.append((source, 0, f"export block #{block.note_id} has empty body"))
            continue
        # Pull structured fields out of the metadata bullets `parse_
        # edit_buffer()` already extracted. `kind` falls back to
        # DEFAULT_KIND when missing, same as the store. `provenance`
        # falls back to "agent" (the historic default; an export
        # written before this import path existed would have had
        # "agent" as its default class, and the round-trip should
        # preserve that class so a re-imported file reads as "agent"
        # not "auto").
        meta_kind = block.meta.get("kind") or DEFAULT_KIND
        if meta_kind not in VALID_KINDS:
            meta_kind = DEFAULT_KIND
        meta_priority = block.meta.get("priority") or "medium"
        meta_provenance = block.meta.get("provenance") or "agent"
        meta_tags = [t.strip() for t in (block.meta.get("tags") or "").split(",") if t.strip()]
        meta_author = block.meta.get("author") or ""
        title = block.title or "(no title)"
        start_line = next(block_iter, 0)
        # Carry the `imported` / `src:` / `src-sha:` tags forward. The
        # `src-sha:` tag is the same `_content_hash(body)` the idempotency
        # check below computes — including it here makes a re-import of
        # the SAME export file a no-op (the import's body, after
        # `body.strip()`, is byte-identical to the original's stored
        # body, since `render_memory_markdown()` also strips before
        # rendering). Without this tag, idempotency would only fire on
        # the non-export path, and re-importing a `vectr memory export`
        # file would create a duplicate set of notes.
        new_tags = sorted(set(meta_tags + [
            _TAG_IMPORTED,
            f"{_TAG_SOURCE_PREFIX}{source.name}",
            f"{_TAG_SOURCE_HASH_PREFIX}{_content_hash(body)}",
        ]))
        planned.append(PlannedNote(
            source_path=source,
            source_start_line=start_line,
            source_end_line=start_line,  # exact end not recoverable from
            # `parse_edit_buffer()` without a re-walk; the round-trip
            # report says "block at line N" which is enough for the
            # user to jump to the file in their editor.
            title=title,
            content=body,
            kind=meta_kind,
            priority=meta_priority,
            tags=new_tags,
            provenance=meta_provenance,
            author_id=meta_author or "import",
        ))
    return planned, errors


# ---------------------------------------------------------------------------
# Idempotency
# ---------------------------------------------------------------------------

def _is_already_imported(
    store: "WorkingContextStore", workspace: str, source: Path, body_text: str,
) -> bool:
    """Idempotency check: is there a note in this workspace whose
    `tags` already contains BOTH `src:<source.name>` AND
    `src-sha:<_content_hash(body_text)>`? Both must match — the
    `src:` tag alone matches every note from the same file (so
    re-imports of the same file would all be skipped), the
    `src-sha:` alone matches notes from different files that
    happen to share content (a contrived case, but a real
    false-positive for a moved file). The AND is the right
    granularity.

    Uses `notes_for_export()` (every note, no recall filtering)
    rather than `recall()` so superseded / revoked / expired notes
    also count: a re-import against a file the user previously
    imported and then revoked MUST still skip, not silently create
    a duplicate alongside the revoked original. The export path's
    broader scope matches what we are checking against (we are
    asking "is this import a no-op", not "would recall return
    this")."""

    expected_src = f"{_TAG_SOURCE_PREFIX}{source.name}"
    expected_sha = f"{_TAG_SOURCE_HASH_PREFIX}{_content_hash(body_text)}"
    for note in store.notes_for_export(workspace):
        tag_set = set(note.tags or [])
        if expected_src in tag_set and expected_sha in tag_set:
            return True
    return False


# ---------------------------------------------------------------------------
# Plan
# ---------------------------------------------------------------------------

def plan_import(
    workspace: Path,
    extra_paths: list[Path] | None,
    store: "WorkingContextStore" | None,
) -> ImportPlan:
    """Build the full import plan: discover candidates, parse each
    file, classify each section, check idempotency, and produce the
    ordered list of `PlannedNote` objects the CLI will either print
    (dry run) or pass to `execute_import()`.

    A `store` argument is required for the idempotency check (we
    must ask the store "is this body already imported?"). A None
    store is allowed only for the no-store dry-run case, where the
    plan is rendered as if every section were new — the dry-run
    output is then "what would be created from scratch", which is
    exactly what a first-time user wants to see.
    """

    workspace = workspace.resolve()
    candidates = _resolve_candidate_files(workspace, extra_paths)
    plan = ImportPlan(source_files=[c.path for c in candidates if c.exists])

    for cand in candidates:
        if not cand.exists or cand.size_bytes == 0:
            continue
        try:
            text = cand.path.read_text(encoding="utf-8")
        except OSError as exc:
            plan.parse_errors.append((cand.path, 0, f"could not read: {exc}"))
            continue
        if not text.strip():
            continue

        # Head text for the export-detect path: the first 2KB is
        # enough to cover `_HEADER_COMMENT` plus the leading kind
        # section headings on any realistic export.
        head_text = text[:2048]
        if _is_export_file(head_text):
            planned, errors = _parse_export_file(text, cand.path)
            # Same idempotency contract as the foreign-file path: a
            # re-import of an unchanged export file plans zero new
            # notes. `_parse_export_file()` already attaches
            # `src-sha:H(body)` to every planned block (so the
            # re-import's body, after the round-trip strip(), hashes
            # to the same tag as the original write), and the same
            # `_is_already_imported()` check the foreign path uses
            # is the one that fires here. Without this branch a
            # second `vectr memory import` against the same
            # `MEMORY.md` would duplicate the entire store.
            if store is not None:
                for note in planned:
                    if _is_already_imported(
                        store, str(workspace), note.source_path, note.content,
                    ):
                        preview = note.content[:40].replace("\n", " ")
                        plan.skipped_existing.append((
                            note.source_path, note.source_start_line, preview,
                        ))
                        continue
                    plan.planned.append(note)
            else:
                plan.planned.extend(planned)
            plan.parse_errors.extend(errors)
            continue

        # Non-export path: split into sections, classify, check
        # idempotency.
        sections = _split_into_sections(text)
        for section in sections:
            body = section.body.strip()
            if len(body) < _MIN_BODY_CHARS:
                preview = body[:40].replace("\n", " ")
                plan.skipped_too_short.append((cand.path, section.start_line, preview))
                continue
            kind, priority, provenance = _infer_kind_and_provenance(section, cand.path)
            title = _make_title(section)
            tags = _build_tags_for_planned(cand.path, section, body)
            if store is not None and _is_already_imported(store, str(workspace), cand.path, body):
                preview = body[:40].replace("\n", " ")
                plan.skipped_existing.append((cand.path, section.start_line, preview))
                continue
            plan.planned.append(PlannedNote(
                source_path=cand.path,
                source_start_line=section.start_line,
                source_end_line=section.end_line,
                title=title,
                content=body,
                kind=kind,
                priority=priority,
                tags=tags,
                provenance=provenance,
            ))
    return plan


# ---------------------------------------------------------------------------
# Execute
# ---------------------------------------------------------------------------

def execute_import(
    store: "WorkingContextStore",
    workspace: str,
    plan: ImportPlan,
) -> ImportResult:
    """Write the planned notes to the store. One `remember()` call
    per planned note, in plan order (which is the same order
    `plan_import()` produced them — section order within each file,
    file order across files). Each call goes through the store's
    normal write path, so the usual write-time guards (auto+directive
    rejection, user_quote binding, scope default resolution, anchor
    hashing) all run exactly as they would for a normal `remember()`
    call. The only difference is the imported tags we attach, which
    carry forward the `imported` / `src:` / `src-sha:` / `src-lines:`
    markers so a future re-import can find and skip them.

    A single failed `remember()` does NOT abort the whole import:
    one bad line in a 200-line file should not lose the other 199.
    Failures are caught, logged via the `note_import_skipped` audit
    shape (the store's own audit mechanism, see
    `agent.working_context_store._audit.py`), and execution continues
    with the next planned note. The CLI summary names every failure
    so the user can fix the file and re-run."""

    result = ImportResult(
        skipped_existing=len(plan.skipped_existing),
        skipped_too_short=len(plan.skipped_too_short),
        parse_errors=len(plan.parse_errors),
    )
    for note in plan.planned:
        try:
            new_id = store.remember(
                workspace,
                note.content,
                tags=note.tags,
                priority=note.priority,
                kind=note.kind,
                title=note.title,
                provenance=note.provenance,
                author_id=note.author_id,
            )
        except ValueError as exc:
            # Most likely cause: an auto+directive that survived the
            # `auto + directive` write-time guard (should be impossible
            # because `_infer_kind_and_provenance` already promotes
            # directives to `agent`, but defensible code is better
            # than code that crashes on a corner case). Log and
            # continue.
            from agent.working_context_store._audit import audit
            audit(
                "NOTE_IMPORT_FAILED", workspace=workspace, source=str(note.source_path),
                title=note.title, error=str(exc),
            )
            result.parse_errors += 1
            continue
        result.written.append((note, new_id))
    return result
