def _content_hash(text: str) -> str:
    """sha256[:16] of `text` — the same fingerprint shape the store
    uses for code-hash staleness checks. Stable across calls and runs;
    identical inputs always give the same tag suffix."""

    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def _infer_kind_and_provenance(
    section: ParsedSection, source: Path | None = None,
) -> tuple[str, str, str]:
    """Classify one parsed section into `(kind, priority, provenance)`.

    The rule, in order:

    1. If the heading starts with an imperative-mode word from
       `_IMPERATIVE_KEYWORDS` (case-insensitive) AND the body is short
       enough to be a single rule (≤ 3 lines of substantive content),
       classify as `kind="directive"`. A directive with a long body is
       almost always a doc-block, not a rule, and the boundary here
       matters: a 200-line block under "MUST" is documentation, not a
       rule, and forcing it to directive would put it in Tier 0
       injection — wrong.

    2. Otherwise, if the SOURCE FILE is in the closed
       `_DIRECTIVE_TYPICAL_FILES` set (CLAUDE.md / AGENTS.md /
       .cursorrules / the editor's instruction file) AND the body is
       short, classify as `kind="directive"`. This is the lane
       brief's "the source file is itself evidence about the kind"
       rule: a heading like `# Test policy` in CLAUDE.md is a much
       stronger candidate for `directive` than the same heading in a
       hand-written `MEMORY.md`. The signal here is the FILE NAME
       (a closed set, not a content heuristic). A long body in a
       directive-typical file still falls back to `finding` (a 200-
       line block under any heading is documentation, not a rule).

    3. Otherwise, classify as `kind="finding"`. The `finding` kind is
       the DEFAULT_KIND and the right home for anything that is not
       a short imperative rule. This is the deliberate "prefer the
       weaker claim" stance the lane brief calls out: a finding that
       should have been a directive merely ranks lower, but a
       directive that should have been a finding gets obeyed
       unconditionally forever.

    4. Provenance: if kind is directive, upgrade from `auto` to
       `agent` so the note survives the `auto + directive` write-time
       guard (see `_store.remember()`). For finding, keep `auto` —
       that's the imported class, and the user can promote a finding
       to agent later via `vectr_promote` or to human via edit.

    5. Priority: rules get `high`; findings get `medium`. A rule that
       carries `kind=directive` but `priority=low` would still be
       Tier 0-injected (kind, not priority, gates that), but a `high`
       priority signals to a reader that the note is meant to be
       acted on, not just stored.
    """

    heading = (section.heading or "").strip()
    body = section.body.strip()
    substantive_lines = [ln for ln in body.splitlines() if ln.strip()]
    short_enough_to_be_a_rule = 0 < len(substantive_lines) <= 3

    heading_first_word = heading.split(maxsplit=1)[0].upper() if heading else ""
    is_imperative_heading = heading_first_word in _IMPERATIVE_KEYWORDS

    is_directive_typical_file = (
        source is not None and _is_directive_typical_file(source)
    )

    if is_imperative_heading and short_enough_to_be_a_rule:
        return "directive", "high", "agent"
    if is_imperative_heading:
        # Long body under an imperative heading: still note that it was
        # declared as a rule, but classify as `finding` so a 200-line
        # doc-block is not Tier 0-injected. The report flags this
        # promotion-via-headword so the user can audit it.
        return "finding", "medium", "auto"
    if is_directive_typical_file and short_enough_to_be_a_rule:
        # The source file is a known rule-bearing instruction file
        # (CLAUDE.md, AGENTS.md, .cursorrules, or a GitHub Copilot
        # instructions file) and the section is short enough to be a
        # rule. Classify as `directive` so the section is Tier 0-
        # injected, matching the way a hand-written `CLAUDE.md` is
        # typically read (the user expects every short section to be
        # a rule, not a learning).
        return "directive", "high", "agent"
    return DEFAULT_KIND, "medium", "auto"


def _make_title(section: ParsedSection) -> str:
    """The title we will store on the new note. Heading if present,
    otherwise the first non-empty body line truncated to 80 chars
    (same shape `_note_title()` already uses for its fallback, kept
    consistent so a re-exported import reads the same as a hand-
    written note)."""

    if section.heading:
        return section.heading[:80]
    first = next((ln.strip() for ln in section.body.splitlines() if ln.strip()), "(no title)")
    return first[:80]


def _build_tags_for_planned(
    source: Path, section: ParsedSection, body_text: str,
) -> list[str]:
    """Tags attached to a single planned note. The `imported` tag is
    the at-read-time signal: a recall that lists a note carrying
    `imported` is telling the user "this came from a file, not from
    this session's observations". The `src:` / `src-sha:` / `src-lines:`
    tags are the at-trace-time signal: a user who wants to know "where
    did this come from?" finds the answer on the note itself, no
    separate lookup required (matches the same load-bearing principle
    the store's anchor-hash design holds to — proof at read time,
    not via a separate audit log).

    Tag list is sorted for determinism; the store dedupes on
    insertion, but sorted order means two `set(tags)`-style tests
    agree."""

    rel_source = source.name  # basename only — the workspace-relative
    # path would leak the user's full filesystem layout into a tag,
    # which the store then echoes at every recall. Basename is enough
    # to identify the file in context.
    return sorted([
        _TAG_IMPORTED,
        f"{_TAG_SOURCE_PREFIX}{rel_source}",
        f"{_TAG_SOURCE_HASH_PREFIX}{_content_hash(body_text)}",
        f"{_TAG_SOURCE_LINES_PREFIX}{section.start_line}-{section.end_line}",
    ])


