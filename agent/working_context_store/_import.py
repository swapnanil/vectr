def _resolve_candidate_files(
    workspace: Path, extra_paths: list[Path] | None,
) -> list[ImportCandidate]:
    """Build the ordered list of source files the importer will try to
    read: every entry in `extra_paths` (user-supplied) first, in the
    order given, then the configured default candidate list (every file
    that actually exists on disk; missing ones are reported as
    `exists=False` but never raised on — a missing default file is the
    common case for a workspace that has never used that filename)."""

    # Read the configured candidate list at call time so a test that
    # monkeypatches MEMORY_IMPORT_CANDIDATE_FILES sees the override.
    from agent.config import MEMORY_IMPORT_CANDIDATE_FILES

    candidates: list[ImportCandidate] = []
    for p in extra_paths or []:
        resolved = p if p.is_absolute() else workspace / p
        try:
            size = resolved.stat().st_size if resolved.exists() else 0
        except OSError:
            size = 0
        candidates.append(ImportCandidate(path=resolved, exists=resolved.exists(), size_bytes=size))
    for rel in MEMORY_IMPORT_CANDIDATE_FILES:
        resolved = workspace / rel
        try:
            size = resolved.stat().st_size if resolved.exists() else 0
        except OSError:
            size = 0
        candidates.append(ImportCandidate(path=resolved, exists=resolved.exists(), size_bytes=size))
    return candidates


def _walk_directory_for_markdown(directory: Path) -> list[Path]:
    """Recursive walk of a user-supplied directory, returning every
    .md / .mdc file. Capped at a sensible depth (8) so a runaway
    walk against `node_modules` or `.git` doesn't burn minutes. The
    caller is responsible for putting the directory under the
    workspace; this function trusts its input."""

    out: list[Path] = []
    if not directory.exists() or not directory.is_dir():
        return out
    for path in directory.rglob("*"):
        if not path.is_file():
            continue
        if path.suffix.lower() not in (".md", ".mdc"):
            continue
        # Cheap depth cap by counting separators in the relative part.
        try:
            rel = path.relative_to(directory)
        except ValueError:
            continue
        depth = len(rel.parts) - 1
        if depth > 8:
            continue
        out.append(path)
    return sorted(out)


