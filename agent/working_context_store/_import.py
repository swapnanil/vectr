# A heading line: starts with 1-6 `#` characters, then a space, then any
# text. Compiled once at module load. Matches the standard CommonMark
# ATX-heading shape a hand-written MEMORY.md uses.
_HEADING_RE = re.compile(r"^(#{1,6})\s+(.+?)\s*$", re.MULTILINE)


def _split_into_sections(text: str) -> list[ParsedSection]:
    """Walk a non-export source file and split it into one
    `ParsedSection` per heading boundary. Sections are 1-indexed by
    their start line; the section's body is everything from the line
    AFTER the heading up to (but not including) the next heading or end
    of file. Headings are stripped from the body — the heading text is
    recorded separately on the section, and re-attaches to the note's
    title in the planned-note shape.

    A file with no headings at all produces one section whose
    `heading` is None and whose body is the whole file. The whole-file
    case is the only one where the granularity choice is forced (no
    boundaries exist), and a "one section per file" outcome is the
    only honest reading.

    Headings inside fenced code blocks are NOT section boundaries —
    the regex matches them, but we walk the file line by line and
    skip the heading-match step while inside a code fence. A heading
    inside a comment-quoted HTML block is the same: a `<!-- ... -->`
    block is treated as code-shaped for this purpose."""

    sections: list[ParsedSection] = []
    lines = text.splitlines()
    if not lines:
        return sections

    in_fence = False
    fence_marker: str | None = None
    in_comment = False
    i = 0
    n = len(lines)
    current_heading: str | None = None
    current_start: int = 1
    body_lines: list[str] = []

    def _flush(end_line: int) -> None:
        body = "\n".join(body_lines).strip()
        if body or current_heading is not None:
            sections.append(ParsedSection(
                heading=current_heading,
                body=body,
                start_line=current_start,
                end_line=end_line,
            ))

    while i < n:
        line = lines[i]
        stripped = line.lstrip()
        # Track fenced code blocks. We deliberately support the
        # CommonMark shape of "at least 3 backticks OR 3 tildes, on a
        # line by themselves or with an info string". An opening fence
        # closes on the next line with the same or longer marker.
        if not in_comment:
            fence_match = re.match(r"^(`{3,}|~{3,})", stripped)
            if fence_match:
                marker = fence_match.group(1)
                if not in_fence:
                    in_fence = True
                    fence_marker = marker[0]  # only the leading char matters for closure
                elif marker[0] == fence_marker and len(marker) >= len(fence_marker):
                    in_fence = False
                    fence_marker = None
                body_lines.append(line)
                i += 1
                continue
        # Track HTML comment blocks. A `<!--` starts one; a `-->` ends
        # one. The export-file header is exactly such a block, and we
        # want to NOT see it as a section boundary either.
        if not in_fence:
            if not in_comment and "<!--" in line:
                in_comment = True
            if in_comment:
                body_lines.append(line)
                if "-->" in line:
                    in_comment = False
                i += 1
                continue
        if not in_fence and not in_comment:
            heading_match = _HEADING_RE.match(line)
            if heading_match:
                # Flush the current section (if any) before opening the new one.
                _flush(i)  # end_line of prior section = line just before this heading (i, 0-indexed in splitlines)
                current_heading = heading_match.group(2).strip()
                current_start = i + 1  # 1-indexed
                body_lines = []
                i += 1
                continue
        body_lines.append(line)
        i += 1

    _flush(n)  # close the last section
    # A trailing-empty-body section is only created if it had a heading;
    # the closing call's `if body or current_heading is not None` handles
    # that. Strip the leading `<!-- ... -->` HTML comment block from the
    # first section's body if it sits there alone (a file whose first
    # thing is the export header is a different code path entirely —
    # this branch is the non-export path, so the comment is just noise).
    return sections


