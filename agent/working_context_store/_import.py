r"""
Import memory files into vectr's working-memory store (UPG-MEMORY-IMPORT).

`vectr memory export` and `vectr memory edit` are the one-way-out and
check-out/check-in paths. This module is the long-missing one-way-in: a
way to bring existing on-disk memory (a hand-written MEMORY.md, an editor's
native instruction file, an editor's native rules dir) into the store
without re-entering it by hand. The full CLI surface sits in main.py's
`cmd_memory` dispatch; this file is the pure translation layer behind it.

Design rules the module explicitly defends:

* Idempotent on content: a re-run of `vectr memory import` against an
  unchanged source file creates zero new notes. Source-line and content
  hash are recorded on the imported note's tags so a later run can find
  and skip it. The check is BY CONTENT, not by note_id, because a re-run
  has no note_ids to compare against — the import path is a one-way
  door.

* Granularity: a source file is NOT one note and NOT one note per line.
  Heading boundaries (Markdown `^#{1,6}\s+`) split it into logical
  sections, the same way a human skims a `MEMORY.md`. A heading-less file
  is one note (a heading-less file is, structurally, a single block of
  text — there is no subdivision to make). A vectr export file is
  detected by its `<!-- Generated by ... -->` header comment and parsed
  through the existing `parse_edit_buffer()` grammar, recovering each
  original block as a note with its declared kind/priority/tags/provenance
  carried forward.

* Provenance: every imported note gets `provenance="auto"` — the same
  class machine-captured facts with no reviewing judgment already carry
  (bm2-design-skeleton.md §5). A hand-written `MEMORY.md` is structurally
  indistinguishable from a generator's output to a parser, so the
  importer does not claim "human" provenance for it. The exceptions are
  narrow and structural, not semantic: a note whose body contains
  imperative-rule markers (the closed keyword set in
  `_IMPERATIVE_KEYWORDS` below) is upgraded to `provenance="agent"`,
  because classify-as-directive + classify-as-auto would be rejected at
  write time (an unreviewed standing rule is a contradiction in terms —
  see `remember()`'s `auto + directive` guard). The promotion is the
  smallest possible deviation from auto, exactly enough to satisfy the
  write-time guard, and the report names every note where it fires so
  the user can audit it.

* Dry run: `--dry-run` prints exactly what would be created (kind,
  title, source file, source-line range, provenance) and changes nothing.
  Memory is the one resource the user cannot easily reconstruct, so dry
  run is the path of first resort — see the CLI's --dry-run help text in
  main.py.

* Discovery: with no `--path`, the module walks a short, closed list of
  default candidate files at the workspace root. With `--path` repeated
  N times, the user can pass any file (or any directory, walked
  recursively for *.md/*.mdc files). The candidate list is configurable
  via `agent.config.MEMORY_IMPORT_CANDIDATE_FILES` (a list of workspace-
  relative paths), with a documented default of
  (`MEMORY.md`, `CLAUDE.md`, `AGENTS.md`, `.cursorrules`,
  `.github/copilot-instructions.md`).

The rail that this module is most careful about: NO query-side heuristics
(Rail 1 in the lane brief). The classifier below is a structural
inspection of TEXT THE USER HANDED US — the file the user pointed at. It
is not inspecting a search query. The keyword set is closed and short
(8 entries); longer lists would cross the line into "let me read the
file and tell you what it means" semantics, which is exactly the failure
the rail is built against.
"""
