# The closed, structural classification set. Short and shallow on
# purpose: a 30-keyword rule list would be "let me read the file and tell
# you what it means" semantics, which Rail 1 forbids. The 8 words below
# are the imperative-mode sentinels a human reader would also notice at a
# glance ("MUST" / "NEVER" / "DO NOT" all signal a rule, not a finding);
# the rule "any one of these in the body AND kind inference below would
# pick directive" is exactly the structural test that makes a directive-
# kinded import survivable through the auto+directive write-time guard.
#
# All keywords are uppercase to make the test stable across both
# imperative ("MUST run tests before commit") and prose ("You must run
# tests before commit") renderings, matching the casing a hand-written
# MEMORY.md typically uses for rule declarations.
_IMPERATIVE_KEYWORDS: tuple[str, ...] = (
    "MUST", "MUST NOT", "NEVER", "ALWAYS", "DO NOT", "DON'T", "REQUIRED", "FORBIDDEN",
)

# Closed list of "directive-typical" source files — the ones the brief
# describes as "holding unconditional directives" rather than "relevance-
# ranked learnings" (CLAUDE.md / .cursorrules / AGENTS.md / the editor's
# native rules file). The lane brief's exact instruction: "The source
# file is itself evidence about the kind. ... Use the file, not just the
# sentence." A heading like `# Test policy` in CLAUDE.md is a much
# stronger candidate for `kind="directive"` than the same heading in a
# hand-written `MEMORY.md`. The structural signal here is the FILE NAME
# (a closed set, not a content heuristic) — Rail 1's "structural
# inspection of text the user handed us" still applies, because the file
# name is the user's own declaration of what they wrote it for.
_DIRECTIVE_TYPICAL_FILES: frozenset[str] = frozenset({
    "CLAUDE.md", "AGENTS.md", ".cursorrules",
    ".github/copilot-instructions.md",
})


def _is_directive_typical_file(source: Path) -> bool:
    """True if `source` is one of the closed `_DIRECTIVE_TYPICAL_FILES`
    paths, matched against the POSIX form of the path. The closed set
    mixes top-level files (`CLAUDE.md`, `AGENTS.md`, `.cursorrules`)
    with one nested file (`.github/copilot-instructions.md`, which
    lives in a `.github/` subdirectory). The basename alone
    (`Path.name`) only matches top-level files, so a strict
    `source.name in _DIRECTIVE_TYPICAL_FILES` check silently misses
    the nested case — a real classifier gap, not a design call.

    The check accepts BOTH an exact POSIX match (the test's bare
    `Path(".github/copilot-instructions.md")` shape) and a
    `"/" + typical` suffix match (the real `Path(workspace /
    ".github/copilot-instructions.md")` shape, which renders to
    `/some/workspace/.github/copilot-instructions.md`). Both
    reduce to the same membership test against the same closed
    set; neither is a content heuristic and neither reads the
    file. The suffix form is anchored to `"/" + typical` so a
    path like `/foo/other-copilot-instructions.md` cannot
    false-positive."""

    posix = source.as_posix()
    for typical in _DIRECTIVE_TYPICAL_FILES:
        if posix == typical or posix.endswith("/" + typical):
            return True
    return False

# Tags we attach to every imported note to support idempotency and
# provenance display. Closed vocabulary — same category as the export
# kind-section labels in _export.py: a fixed protocol string, not
# caller-tunable.
_TAG_IMPORTED = "imported"
_TAG_SOURCE_PREFIX = "src:"           # "src:MEMORY.md" — human-readable source label
_TAG_SOURCE_HASH_PREFIX = "src-sha:"   # "src-sha:<16 hex>" — content fingerprint at import
_TAG_SOURCE_LINES_PREFIX = "src-lines:"  # "src-lines:12-34" — line range in the source file

# The minimum length of a body for the importer to consider it a note.
# Shorter blocks (a single line of text, a stray heading with no body,
# a fragment of boilerplate) are skipped with a "skipped: too short"
# report line, not silently absorbed. The 8-character floor matches
# `_note_title()`'s 80-char ceiling on the other end: a 1-character body
# carries no recoverable content anyway.
_MIN_BODY_CHARS = 8


@dataclass
class ImportCandidate:
    """One source file the importer is about to read, with the resolved
    path and the line-count the candidate scanner recorded before parsing
    (used by the report to distinguish "file not found" from "file
    empty")."""

    path: Path
    exists: bool
    size_bytes: int


@dataclass
class ParsedSection:
    """One chunk of a non-export source file: the heading line (or
    `None` for a heading-less file's single body), the heading's line
    number in the source file, and the body. Line numbers are 1-indexed
    and recorded so the report can name "lines 12-34" — the line range
    the user can jump to in their editor to verify what was imported.
    """

    heading: str | None
    body: str
    start_line: int
    end_line: int


@dataclass
class PlannedNote:
    """One note the importer is about to write. The fields are the exact
    values the eventual `store.remember()` call will use; the dry-run
    report and the actual-write report are both formatted straight off
    this shape so they cannot disagree about what a note is."""

    source_path: Path
    source_start_line: int
    source_end_line: int
    title: str
    content: str
    kind: str
    priority: str
    tags: list[str]
    provenance: str
    author_id: str = "import"


@dataclass
class ImportPlan:
    """The full output of `plan_import()`: every note the importer would
    create from every source file, plus the per-source statistics the
    report needs. `skipped_too_short` and `skipped_existing` are recorded
    separately from `planned` so a re-run's report can name what was
    found and what was reused rather than only what was new — the
    opposite of a silent no-op that would let a user think they re-
    imported when they didn't."""

    source_files: list[Path]
    planned: list[PlannedNote] = field(default_factory=list)
    skipped_too_short: list[tuple[Path, int, str]] = field(default_factory=list)  # (path, line, preview)
    skipped_existing: list[tuple[Path, int, str]] = field(default_factory=list)  # (path, line, preview)
    parse_errors: list[tuple[Path, int, str]] = field(default_factory=list)  # (path, line, reason)

    def is_empty(self) -> bool:
        return not self.planned and not self.skipped_too_short and not self.parse_errors


@dataclass
class ImportResult:
    """The actual-write output: one entry per new note written, with the
    new note_id the store assigned. Skipped counts are echoed so the CLI
    can format a one-line summary that doesn't require re-walking the
    plan."""

    written: list[tuple[PlannedNote, int]] = field(default_factory=list)  # (plan, new_note_id)
    skipped_existing: int = 0
    skipped_too_short: int = 0
    parse_errors: int = 0


