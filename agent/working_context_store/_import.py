def _is_export_file(head_text: str) -> bool:
    """True if the file's first ~512 bytes contain the exact
    `_EXPORT_HEADER_COMMENT` sentinel that `render_memory_markdown()`
    always emits as its first line. The sentinel is the same constant
    `_export.py` writes, so a round-trip detection is exact and
    structural (no heuristic, no tail-match on `Working Memory`) —
    a hand-written `MEMORY.md` that happens to contain the words
    "Working Memory" is NOT misclassified as an export."""

    if not head_text:
        return False
    return _EXPORT_HEADER_COMMENT in head_text[:2048]


